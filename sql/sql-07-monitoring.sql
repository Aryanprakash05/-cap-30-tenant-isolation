SELECT COUNT(*) FROM ANALYTICS.V_CUSTOMER;

USE ROLE TENANT_B_ANALYST;
USE SECONDARY ROLES NONE;
USE WAREHOUSE CAPSTONE_WH;

ALTER SESSION SET QUERY_TAG = 'tenant=EA,role=TENANT_B_ANALYST';

SELECT COUNT(*) FROM ANALYTICS.V_CUSTOMER;

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE CAPSTONE_WH;

SELECT WAREHOUSE_NAME, START_TIME, END_TIME, CREDITS_USED FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY WHERE WAREHOUSE_NAME = 'CAPSTONE_WH' ORDER BY START_TIME DESC LIMIT 10;

SELECT ROLE_NAME, QUERY_TAG, COUNT(*) AS queries, SUM(TOTAL_ELAPSED_TIME) / 1000 AS total_seconds FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY WHERE WAREHOUSE_NAME = 'CAPSTONE_WH' AND START_TIME >= DATEADD(day, -7, CURRENT_TIMESTAMP()) GROUP BY ROLE_NAME, QUERY_TAG ORDER BY ROLE_NAME, QUERY_TAG;

SELECT ROLE_NAME, COUNT(*) AS queries FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY WHERE WAREHOUSE_NAME = 'CAPSTONE_WH' AND START_TIME >= DATEADD(day, -7, CURRENT_TIMESTAMP()) GROUP BY ROLE_NAME ORDER BY queries DESC;
